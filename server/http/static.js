// server/http/static.js — the static file server (routes.js hands it every GET / HEAD that is not an API route):
// (i18n-ignore-file: the error pages are bilingual by design, 中文 · English — docs/I18N.md)
//
//     /        → public/      (index.html for directories)
//     /data/   → data/        (generated game data)
//     /shared/ → shared/      (ESM shared with the browser)
//     /sim/    → server/sim/  (the battle simulation, read-only, `.js` only — client-side
//                              combat, DESIGN §14; the Node-only loader nodeData.js is not served)
//     /data.js → a generated browser stand-in of server/data.js (the sim's content modules
//                import `../../../data.js`; in the browser it serves the data injected with
//                /sim/simdata.js setSimData). No other server file is ever served.
//     /media/bgm/act1 → public/assets/audio/bgm/act1.mp3 — the same audio files, addressed
//                **without** an extension so download managers (IDM / 迅雷 …) stop popping a
//                "下载文件信息" dialog for every BGM track (media.js, shared/media.js, public/js/media.js)
//     /packs/index.json → the content packs of this server (server/packs.js: the language packs of
//                public/i18n/ and the pack folders of packs/, re-read when they change; never cached)
//     /packs/<id>/<file> → a file of a pack folder — only one its manifest names (server/packs.js servable)
//
// Traversal & dotfile protection, a directory without its trailing slash → 301, 404 page; an absent
// data/local-assets.json or data/local-fx.json is answered with an empty manifest. Files go out through files.js serveFile.

import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import { gunzipSync } from 'node:zlib';
import { MEDIA_PREFIX } from '../../shared/media.js';
import { ROOT, noopLog } from './config.js';
import { sendError, sendJson } from './common.js';
import { MIME, GzipCache, isNotModified, serveFile, acceptsGzip } from './files.js';
import { serveMedia } from './media.js';
import { createPackRegistry } from '../packs.js';
import { PACKS_URL, PACK_INDEX_FILE } from '../../shared/packs.js';

/** Browser stand-in of server/data.js, served at /data.js (see the header). Served byte for byte: its first line names the entry, server/index.js. */
export const DATA_SHIM_JS = `// Generated by server/index.js — browser stand-in for server/data.js (DESIGN §14 client-side combat).
// The simulation's content modules (/sim/content/support/index.js) import getData() from here; it returns the game data
// the page injected with /sim/simdata.js setSimData(data).
import { getSimData } from './sim/simdata.js';
export function getData() { return getSimData() || {}; }
export function resetData() {}
`;
/** Files under server/sim that are never served (Node-only). */
const SIM_PRIVATE = new Set(['nodedata.js']); // lower-case (compared case-insensitively)

// ---------------------------------------------------------------------------------------------------
// Static file handler
// ---------------------------------------------------------------------------------------------------

/** Optional per-machine manifests (tools/local-extract) and the empty stand-ins served when they are absent. */
const LOCAL_ART_MANIFEST = 'local-assets.json';
const LOCAL_MANIFESTS = new Set([LOCAL_ART_MANIFEST, 'local-fx.json']);
const EMPTY_LOCAL_ART = Buffer.from(JSON.stringify({ version: 1, source: 'none', count: 0, groups: {} }));
const EMPTY_LOCAL_FX = Buffer.from(JSON.stringify({ version: 1, groups: {} }));
/** The git-ignored install-time folders of `public/` (tools/vendor.mjs, tools/fetch-assets.mjs). */
const INSTALL_PUBLIC_DIRS = ['assets', 'vendor', 'fonts'];

/**
 * Create the static request handler.
 * @param {{ publicDir: string, dataDir: string, sharedDir: string, simDir?: string, packsDir?: string,
 *   packs?: ReturnType<typeof createPackRegistry>, installDir?: string, log?: object,
 *   independentEngineArchives?: { revision: string, files: Record<string, string> } }} dirs
 *   packs: the server's pack registry (default: one over publicDir, dataDir and packsDir — ROOT/packs)
 *   installDir: a full install (STRONGHOLD_INSTALL_DIR) whose public/assets|vendor|fonts and dev pages this checkout
 *   serves read-only when it has none of its own (its own folders always win); its data/local-assets.json is the
 *   manifest of the art it serves
 * @returns {(req: import('node:http').IncomingMessage, res: import('node:http').ServerResponse, rawPath: string, query: string) => Promise<void>}
 */
export function createStaticHandler({ publicDir, dataDir, sharedDir, simDir = path.join(ROOT, 'server', 'sim'), packsDir = path.join(ROOT, 'packs'), packs = null, installDir = null, assaultAssetsDir = null, independentEngineArchives = null, log = noopLog }) {
  if (assaultAssetsDir && !path.isAbsolute(assaultAssetsDir)) throw new TypeError('assaultAssetsDir must be absolute');
  const registry = packs || createPackRegistry({ publicDir, dataDir, packsDir }, { log: /** @type {any} */ (log) });
  // A checkout without its own install (a Git worktree) can serve another install's art, vendored libraries and
  // fonts read-only, so nothing is copied or linked into the checkout.
  // Resolve install art per file below. A checkout can contain only part of an ignored folder, so
  // directory existence cannot decide whether the whole install copy is hidden.
  const installPublicDirs = installDir ? new Map(INSTALL_PUBLIC_DIRS.map((name) => [name, path.resolve(installDir, 'public', name)])) : new Map();
  const mediaPublicDir = publicDir;
  const fallbackAudioDir = assaultAssetsDir ? path.join(path.resolve(assaultAssetsDir), 'audio') : null;
  const mediaFallbackDirs = [installDir ? path.resolve(installDir, 'public', 'assets', 'audio') : null, fallbackAudioDir].filter(Boolean);
  // dev pages (public/dev/) the checkout does not have come from the install's: demos kept untracked in the install
  // stay reachable while every page of the game is the checkout's own (a checkout file always wins)
  const devDir = installDir && path.resolve(installDir, 'public', 'dev') !== path.resolve(publicDir, 'dev') ? path.resolve(installDir, 'public', 'dev') : null;
  const mounts = [
    ...(assaultAssetsDir ? [{ prefix: '/assault-assets/', name: 'public', dir: path.resolve(assaultAssetsDir),
      only: new Set(['.png', '.jpg', '.jpeg', '.webp', '.skel', '.atlas', '.json']) }] : []),
    // Isolated, read-only browser namespace for the Assault client engine. These virtual prefixes expose only
    // ESM files from the same source directories; the sim's private Node loader remains denied.
    { prefix: '/assault-engine/server/sim/', name: 'assault-sim', dir: path.resolve(simDir),
      only: new Set(['.js']), deny: SIM_PRIVATE },
    { prefix: '/assault-engine/shared/', name: 'assault-shared', dir: path.resolve(sharedDir), only: new Set(['.js']) },
    { prefix: '/data/', name: 'data', dir: path.resolve(dataDir) },
    { prefix: '/shared/', name: 'shared', dir: path.resolve(sharedDir) },
    // the simulation: ES modules only (no directory listings, no other file types, no Node-only loader)
    { prefix: '/sim/', name: 'sim', dir: path.resolve(simDir), only: new Set(['.js']), deny: SIM_PRIVATE },
    { prefix: '/', name: 'public', dir: path.resolve(publicDir) },
  ];
  const shimBody = Buffer.from(DATA_SHIM_JS);
  const shimTag = `"shim-${shimBody.length.toString(16)}"`;
  const gzipCache = new GzipCache();
  const engineArchives = new Map();
  if (independentEngineArchives) {
    const names = ['server/data.js', 'server/modes/independent/catalog.js'];
    if (!/^[a-f0-9]{40}$/.test(independentEngineArchives.revision) ||
      Object.keys(independentEngineArchives.files).length !== names.length ||
      names.some((name) => !Object.hasOwn(independentEngineArchives.files, name)))
      throw new TypeError('Independent engine archives require the native Git revision and both generated shims');
    for (const name of names) {
      const archive = independentEngineArchives.files[name];
      if (!path.isAbsolute(archive) || !archive.endsWith('.gz') || !fs.lstatSync(archive).isFile() || fs.lstatSync(archive).isSymbolicLink())
        throw new TypeError('Independent engine archives must be explicit ordinary absolute gzip paths');
      const gzip = fs.readFileSync(archive), body = gunzipSync(gzip);
      if (!body.subarray(0, 80).toString().startsWith('// Generated by tools/build-client-engine.mjs'))
        throw new TypeError('Independent engine archive is not a generated shim');
      engineArchives.set(`/js/independent/engine/${name}`, { gzip, body,
        tag: `"independent-engine-${independentEngineArchives.revision}-${name}"` });
    }
  }

  return async function serveStatic(req, res, rawPath, query) {
    let decoded;
    try { decoded = decodeURIComponent(rawPath); } catch { sendError(req, res, 400, '请求地址无效 · Bad request'); return; }
    if (!decoded.startsWith('/') || decoded.includes('\0') || decoded.includes('\\')) {
      sendError(req, res, 400, '请求地址无效 · Bad request');
      return;
    }
    // The manifests describe the local art and effects mounted from installDir, so an installed copy wins over a stale
    // checkout data/local-assets.json or data/local-fx.json. Other /data files continue through the ordinary
    // checkout-first mount.
    if (decoded.startsWith('/data/') && LOCAL_MANIFESTS.has(decoded.slice(6)) && installDir) {
      const installedManifest = path.resolve(installDir, 'data', decoded.slice(6));
      try {
        const installedStat = await fsp.stat(installedManifest);
        if (installedStat.isFile()) {
          await serveFile(req, res, installedManifest, installedStat, 'data', [decoded.slice(6)], query, gzipCache, log);
          return;
        }
      } catch (e) {
        if (!e || (e.code !== 'ENOENT' && e.code !== 'ENOTDIR')) {
          log.error('[http] install local art manifest stat failed', e);
          sendError(req, res, 500, '服务器内部错误 · Internal error');
          return;
        }
      }
    }
    if (decoded === '/data.js' || decoded === '/assault-engine/server/data.js') {
      const headers = { 'Content-Type': MIME['.js'], 'Cache-Control': 'no-cache', ETag: shimTag, 'Content-Length': shimBody.length };
      if (isNotModified(req, shimTag, new Date(0))) { delete headers['Content-Length']; res.writeHead(304, headers); res.end(); return; }
      res.writeHead(200, headers);
      res.end(req.method === 'HEAD' ? undefined : shimBody);
      return;
    }
    const archivedEngine = engineArchives.get(decoded);
    if (archivedEngine && !fs.existsSync(path.join(publicDir, decoded.slice(1)))) {
      const compressed = acceptsGzip(req.headers['accept-encoding']);
      const body = compressed ? archivedEngine.gzip : archivedEngine.body;
      const headers = { 'Content-Type': MIME['.js'], 'Cache-Control': 'no-cache', Vary: 'Accept-Encoding',
        ETag: archivedEngine.tag, 'Content-Length': body.length,
        ...(compressed ? { 'Content-Encoding': 'gzip' } : {}) };
      if (req.headers['if-none-match'] === archivedEngine.tag) {
        delete headers['Content-Length']; res.writeHead(304, headers); res.end(); return;
      }
      res.writeHead(200, headers); res.end(req.method === 'HEAD' ? undefined : body); return;
    }
    // Content packs (server/packs.js): the live index, and only the files a pack's manifest names
    if (decoded.startsWith(PACKS_URL)) {
      const parts = decoded.slice(PACKS_URL.length).split('/');
      if (parts.length === 1 && parts[0] === PACK_INDEX_FILE) { sendJson(req, res, 200, registry.index()); return; }
      const abs = parts.length >= 2 && !parts.some((s) => s === '' || s === '.' || s === '..') ? registry.servable(parts[0], parts.slice(1).join('/')) : null;
      const st = abs ? await fsp.stat(abs).catch(() => null) : null;
      if (!st || !st.isFile()) { sendError(req, res, 404, '页面不存在 · Not found', decoded.length <= 200 ? decoded : ''); return; }
      await serveFile(req, res, abs, st, 'packs', parts, query, gzipCache, log);
      return;
    }
    // Extension-less audio (download-manager avoidance): /media/bgm/act1 → /assets/audio/bgm/act1.mp3
    if (decoded.startsWith(MEDIA_PREFIX)) {
      await serveMedia(req, res, decoded.slice(MEDIA_PREFIX.length), query, mediaPublicDir, gzipCache, log, mediaFallbackDirs);
      return;
    }
    // In Assault opt-in mode, direct audio URLs share /media/ resolution so canonical audio wins and the
    // isolated asset root can supply only missing files. Other modes keep the existing public mount unchanged.
    if (fallbackAudioDir && decoded.startsWith('/assets/audio/')) {
      await serveMedia(req, res, decoded.slice('/assets/audio/'.length), query, mediaPublicDir, gzipCache, log, mediaFallbackDirs);
      return;
    }
    // Bare mount paths (e.g. "/data") → treat as the mount directory.
    const mount = mounts.find((m) => decoded.startsWith(m.prefix) || decoded === m.prefix.slice(0, -1)) || mounts[mounts.length - 1];
    const rest = decoded.length > mount.prefix.length ? decoded.slice(mount.prefix.length) : '';
    const segments = rest.split('/').filter((s) => s.length > 0);
    if (segments.some((s) => s === '..' || s === '.')) { sendError(req, res, 403, '禁止访问 · Forbidden'); return; }
    if (segments.some((s) => s.startsWith('.'))) { sendError(req, res, 404, '页面不存在 · Not found'); return; }
    if (mount.only && (!segments.length || !mount.only.has(path.extname(segments[segments.length - 1]).toLowerCase())
      // (case-insensitive: the host may be Windows / macOS, where NODEDATA.JS opens nodeData.js)
      || (mount.deny && mount.deny.has(segments[segments.length - 1].toLowerCase())))) {
      sendError(req, res, 404, '页面不存在 · Not found');
      return;
    }
    let absPath = path.join(mount.dir, ...segments);
    if (absPath !== mount.dir && !absPath.startsWith(mount.dir + path.sep)) { sendError(req, res, 403, '禁止访问 · Forbidden'); return; }

    let stat;
    let viaDirectory = false;
    try {
      stat = await fsp.stat(absPath);
      if (stat.isDirectory()) {
        if (!decoded.endsWith('/')) {
          // Built from normalized segments (never from the raw path) so "//host" can't become an open redirect.
          const loc = (mount.prefix + segments.map(encodeURIComponent).join('/') + '/').replace(/\/{2,}/g, '/');
          res.writeHead(301, { Location: loc + (query ? `?${query}` : ''), 'Cache-Control': 'no-cache', 'Content-Length': 0 });
          res.end();
          return;
        }
        absPath = path.join(absPath, 'index.html');
        segments.push('index.html');
        viaDirectory = true;
        stat = await fsp.stat(absPath);
      }
      // Not a regular file, or a file addressed like a directory ("/app.js/") → 404.
      if (!stat.isFile() || (decoded.endsWith('/') && !viaDirectory)) {
        throw Object.assign(new Error('not a file'), { code: 'ENOENT' });
      }
      if (mount.deny) {
        // the on-disk name decides (case-insensitive file systems, Windows 8.3 short names like NODEDA~1.JS)
        const real = await fsp.realpath(absPath);
        if (mount.deny.has(path.basename(real).toLowerCase())) throw Object.assign(new Error('private'), { code: 'ENOENT' });
      }
    } catch (e) {
      // Source-owned public files take precedence. Only a genuinely missing source file permits
      // the exact corresponding read-only install file; permission and other errors stay visible.
      const installPublicName = mount.name === 'public' && mount.prefix === '/' ? segments[0] : null;
      const installPublicDir = installPublicName && installPublicDirs.get(installPublicName);
      if (installPublicDir && (e?.code === 'ENOENT' || e?.code === 'ENOTDIR') && segments.length > 1 && !decoded.endsWith('/')) {
        const installPath = path.resolve(installPublicDir, ...segments.slice(1));
        if (installPath.startsWith(installPublicDir + path.sep)) {
          try {
            const installStat = await fsp.stat(installPath);
            if (installStat.isFile()) {
              await serveFile(req, res, installPath, installStat, mount.name, segments, query, gzipCache, log);
              return;
            }
          } catch (installError) {
            if (!installError || (installError.code !== 'ENOENT' && installError.code !== 'ENOTDIR')) {
              log.error('[http] install public file stat failed', installError);
              sendError(req, res, installError.code === 'EACCES' || installError.code === 'EPERM' ? 403 : 500,
                installError.code === 'EACCES' || installError.code === 'EPERM' ? '禁止访问 · Forbidden' : '服务器内部错误 · Internal error');
              return;
            }
          }
        }
      }
      const installManifest = installDir && segments.length === 1 && LOCAL_MANIFESTS.has(segments[0])
        ? path.resolve(installDir, 'data', segments[0]) : null;
      const devPath = e && e.code === 'ENOENT' && devDir && mount.prefix === '/' && segments[0] === 'dev' && segments.length > 1 && !decoded.endsWith('/')
        ? path.join(devDir, ...segments.slice(1)) : null;
      const devStat = devPath && devPath.startsWith(devDir + path.sep) ? await fsp.stat(devPath).catch(() => null) : null;
      if (devStat && devStat.isFile()) {
        await serveFile(req, res, devPath, devStat, mount.name, segments, query, gzipCache, log);
      } else if (e && e.code === 'ENOENT' && mount.name === 'data' && segments.length === 1 && LOCAL_MANIFESTS.has(segments[0])
        && installManifest && fs.existsSync(installManifest)) {
        // the per-machine manifests belong to the install whose public/assets/local is served (installDir above)
        await serveFile(req, res, installManifest, await fsp.stat(installManifest), mount.name, segments, query, gzipCache, log);
      } else if (e && e.code === 'ENOENT' && mount.name === 'data' && segments.length === 1 && LOCAL_MANIFESTS.has(segments[0])) {
        // Optional per-machine extraction output (DESIGN §13, §33.1): an install without it gets an empty manifest
        // instead of a 404, so browsers don't log an error on every page load. Clients treat empty groups as "none".
        const empty = segments[0] === LOCAL_ART_MANIFEST ? EMPTY_LOCAL_ART : EMPTY_LOCAL_FX;
        res.writeHead(200, { 'Content-Type': MIME['.json'], 'Cache-Control': 'no-cache', 'Content-Length': empty.length });
        res.end(req.method === 'HEAD' ? undefined : empty);
      } else if (e && (e.code === 'ENOENT' || e.code === 'ENOTDIR' || e.code === 'EISDIR' || e.code === 'ENAMETOOLONG')) {
        sendError(req, res, 404, '页面不存在 · Not found', decoded.length <= 200 ? decoded : '');
      } else if (e && (e.code === 'EACCES' || e.code === 'EPERM')) {
        sendError(req, res, 403, '禁止访问 · Forbidden');
      } else {
        log.error('[http] stat failed', e);
        sendError(req, res, 500, '服务器内部错误 · Internal error');
      }
      return;
    }
    await serveFile(req, res, absPath, stat, mount.name, segments, query, gzipCache, log);
  };
}
