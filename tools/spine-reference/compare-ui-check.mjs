import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath,pathToFileURL} from 'node:url';

const here=path.dirname(fileURLToPath(import.meta.url));
const project='E:/WindowsWorkspace/webworks/apps/stronghold-protocol';
const {previewServer}=await import(pathToFileURL(path.join(project,'tools/spine-reference/preview-server.mjs')).href);
const out=path.join(project,'runtime/spine-compare-20261008/ui');
const require=createRequire(path.join(project,'package.json'));
const puppeteer=require('puppeteer-core');
const chrome='C:/Users/lilithgames/AppData/Local/ms-playwright/chromium_headless_shell-1234/chrome-headless-shell-win64/chrome-headless-shell.exe';
await fs.mkdir(out,{recursive:true});
const report={startedAt:new Date().toISOString(),checks:{},errors:[],files:{}};
let server,browser,timer;
const timeout=new Promise((_,reject)=>{timer=setTimeout(()=>reject(new Error('检查超过 120 秒硬截止')),120000);});
try{
 server=await previewServer({publicRoot:path.resolve(here,'../../public'),installRoot:project});
 browser=await Promise.race([puppeteer.launch({executablePath:chrome,headless:true,args:['--no-sandbox','--disable-dev-shm-usage']}),timeout]);
 const page=await browser.newPage({viewport:{width:1500,height:1000}}),pageErrors=[];
 page.on('pageerror',e=>pageErrors.push(String(e)));
 page.on('console',m=>{if(m.type()==='error')pageErrors.push(m.text());});
 const pageUrl=server.url+'/dev/spine-reference/compare.html';
 await Promise.race([page.goto(pageUrl,{waitUntil:'networkidle0',timeout:60000}),timeout]);
 await Promise.race([page.waitForFunction(()=>window.__ready===true||window.__error,{timeout:60000}),timeout]);
 const init=await page.evaluate(()=>({ready:window.__ready,error:window.__error,profiles:[...document.querySelectorAll('#profiles label')].map(x=>x.textContent),cols:document.querySelectorAll('.col').length}));
 if(!init.ready)throw new Error(init.error||'页面初始化未完成');
 report.checks.initial=init;
 const ids=await page.evaluate(()=>[...document.querySelectorAll('#profiles input:checked')].map(x=>x.value));
 const has2b=ids.includes('2b-front'),hasSurtr=ids.includes('surtr-front');
 report.checks.profileCoverage={ids,has2b,hasSurtr};
 if(!has2b||!hasSurtr)throw new Error('默认比较组缺少 2B 或 Surtr');
 const anims=await page.evaluate(()=>[...document.querySelectorAll('.col select')].map(s=>({title:s.closest('.col').querySelector('strong').textContent,value:s.value,options:[...s.options].map(o=>o.value)})));
 report.checks.animations=anims;
 report.checks.locatorLinks=await page.evaluate(()=>[...document.querySelectorAll('[data-col-link]')].map(a=>({href:a.href,source:a.dataset.source,point:new URL(a.href).searchParams.get('point'),sources:new URL(a.href).searchParams.get('sources')})));
 if(report.checks.locatorLinks.some(x=>x.sources!==x.source||!x.point))throw new Error('单列定位链接缺少本列素材或所选语义点');
 report.checks.unknowns=await page.evaluate(()=>[...window.compare.states].map(([id,s])=>({id,unknown:Object.values(s.pose.landmarks).filter(p=>p.status==='unknown').map(p=>p.id)})));
 if(!report.checks.unknowns.some(x=>x.unknown.length))throw new Error('页面未显示任何未标定语义点');
 await page.click('#play');
 report.checks.playPause=await page.evaluate(()=>({label:document.querySelector('#play').textContent,playing:document.querySelector('#play').textContent==='暂停'}));
 if(!report.checks.playPause.playing)throw new Error('播放按钮未切换至暂停态');
 await page.click('#play');
 await page.evaluate(()=>{document.querySelector('#align').value='progress';const t=document.querySelector('#time');t.value='.42';t.dispatchEvent(new Event('input',{bubbles:true}));});
 const drag=await page.evaluate(()=>({time:window.compare.getTime(),url:new URL(location.href).searchParams.get('t')}));
 if(Math.abs(drag.time-.42)>.002)throw new Error('时间拖动没有更新比较进度');
 report.checks.progressDrag=drag;
 await page.evaluate(()=>{document.querySelector('#align').value='seconds';document.querySelector('#align').dispatchEvent(new Event('change',{bubbles:true}));document.querySelector('#time').value='.25';document.querySelector('#time').dispatchEvent(new Event('input',{bubbles:true}));});
 report.checks.secondsAlignment=await page.evaluate(()=>({align:document.querySelector('#align').value,time:window.compare.getTime(),url:new URL(location.href).searchParams.get('align')}));
 await page.evaluate(()=>{const z=document.querySelector('#zoom');z.value='1.25';z.dispatchEvent(new Event('input',{bubbles:true}));});
 const link=await page.evaluate(()=>location.href);
 await Promise.race([page.goto(link,{waitUntil:'networkidle0',timeout:60000}),timeout]);
 await Promise.race([page.waitForFunction(()=>window.__ready===true||window.__error,{timeout:60000}),timeout]);
 report.checks.urlRoundTrip=await page.evaluate(()=>({ready:window.__ready,align:document.querySelector('#align').value,t:new URL(location.href).searchParams.get('t'),zoom:new URL(location.href).searchParams.get('zoom'),columns:document.querySelectorAll('.col').length}));
 if(!report.checks.urlRoundTrip.ready)throw new Error('URL 回载失败');
 if(report.checks.urlRoundTrip.zoom!=='1.25')throw new Error('缩放值没有经 URL 往返');
 await page.evaluate(()=>{document.querySelector('#original').checked=true;document.querySelector('#original').dispatchEvent(new Event('change',{bubbles:true}));});
 report.checks.originalOverlay=await page.evaluate(()=>({checked:document.querySelector('#original').checked,canvases:[...document.querySelectorAll('.col canvas')].map(c=>({hidden:c.classList.contains('hide'),width:c.width,height:c.height})),svgVisible:[...document.querySelectorAll('.col svg')].every(s=>!s.classList.contains('hide'))}));
 report.checks.pixelAlignment=await page.evaluate(()=>[...window.compare.states].flatMap(([id,s])=>['arm.L.wrist','leg.L.knee'].map(point=>{const data=s.pose.landmarks[point],circle=s.svg.querySelector(`[data-point="${point}"]`),box=circle.getBoundingClientRect(),svgPoint={x:(box.left+box.right)/2,y:(box.top+box.bottom)/2},global=s.sp.toGlobal(new PIXI.Point(data.position[0],-data.position[1])),canvas=s.article.querySelector('canvas'),rect=canvas.getBoundingClientRect(),pixiPoint={x:rect.left+global.x*rect.width/canvas.width,y:rect.top+global.y*rect.height/canvas.height};return{source:id,point,svgPoint,pixiPoint,deltaPx:Math.hypot(svgPoint.x-pixiPoint.x,svgPoint.y-pixiPoint.y)};})));
 if(report.checks.pixelAlignment.some(x=>!Number.isFinite(x.deltaPx)||x.deltaPx>2))throw new Error('原图与语义 SVG 的腕/膝坐标偏差超过 2px');
 await page.evaluate(()=>document.querySelectorAll('.col svg').forEach(s=>s.style.visibility='hidden'));
 await page.screenshot({path:path.join(out,'canvas-only.png'),fullPage:true});
 report.files.canvasOnly=path.join(out,'canvas-only.png');
 await page.evaluate(()=>{document.querySelectorAll('.col svg').forEach(s=>s.style.visibility='visible');document.querySelectorAll('.col canvas').forEach(c=>c.classList.add('hide'));});
 await page.screenshot({path:path.join(out,'svg-only.png'),fullPage:true});
 report.files.svgOnly=path.join(out,'svg-only.png');
 await page.evaluate(()=>document.querySelectorAll('.col canvas').forEach(c=>c.classList.remove('hide')));
 await page.screenshot({path:path.join(out,'compare-ui.png'),fullPage:true});
 report.files.screenshot=path.join(out,'compare-ui.png');
 const locatorPage=await browser.newPage();
 await locatorPage.goto(report.checks.locatorLinks[0].href,{waitUntil:'networkidle0',timeout:60000});
 await locatorPage.waitForFunction(()=>window.__ready===true||window.__error,{timeout:60000});
 report.checks.singleColumnLocator=await locatorPage.evaluate(()=>({sources:[...document.querySelectorAll('#profiles input:checked')].map(x=>x.value),columns:document.querySelectorAll('.col').length,point:new URL(location.href).searchParams.get('point')}));
 await locatorPage.close();
 await page.goto(server.url+'/dev/spine-reference/index.html?source=2b-front&animation=Attack',{waitUntil:'networkidle0',timeout:60000});
 await page.waitForFunction(()=>window.__ready===true||window.__error,{timeout:60000});
 await page.screenshot({path:path.join(out,'single-reference-baseline.png'),fullPage:true});
 report.files.singleReferenceBaseline=path.join(out,'single-reference-baseline.png');
 report.checks.pageErrors=pageErrors;
 if(pageErrors.length)throw new Error(`浏览器报告错误：${pageErrors.join(' | ')}`);
}catch(e){report.errors.push(String(e.stack||e));}
finally{
 clearTimeout(timer);
 if(browser)await browser.close().catch(e=>report.errors.push(`browser close: ${e}`));
 if(server)await server.close().catch(e=>report.errors.push(`server close: ${e}`));
 report.finishedAt=new Date().toISOString();
 report.ok=report.errors.length===0;
 report.files.report=path.join(out,'compare-ui-check.json');
 await fs.writeFile(report.files.report,JSON.stringify(report,null,2));
 console.log(JSON.stringify(report,null,2));
}
if(!report.ok)process.exitCode=1;
