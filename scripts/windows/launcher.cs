// scripts/windows/launcher.cs — 启动游戏.exe, the Windows launcher of the portable bundle and the installers
// (docs/WINDOWS.md). Built by scripts/make-windows-bundle.mjs with the C# compiler of the .NET Framework 4.x that ships
// with Windows 10/11, so the exe runs on a clean machine without installing anything.
//
// It is a console program on purpose: the console window is the visible progress of the first-run resource download
// (tools/setup.mjs → tools/fetch-assets.mjs), it shows the addresses to share, and closing it stops the server —
// Windows sends CTRL_CLOSE_EVENT to every process attached to the console, the node processes included, exactly
// like the .bat it replaces. Everything else stays in app\scripts\launch.mjs: if our server already answers on the
// port it only opens the browser, otherwise it prepares resources, starts the server and opens the browser.
//
//   启动游戏.exe [launch.mjs options…]      e.g. 启动游戏.exe --port 3001
//
// Saves: the workshop keeps its runs on the server side (server/index.js, SP_INDEPENDENT_DIRECTORY). The launcher
// points that at %LOCALAPPDATA%\Stronghold-Protocol-Workshop\independent-sessions so uninstalling, upgrading or
// unpacking a new version into another folder keeps them; runs left in a previous bundle's
// app\runtime\independent-sessions are copied there once. An SP_INDEPENDENT_DIRECTORY set by the user wins.
//
// BuildInfo (launch arguments and version) is generated by the bundle script next to this file at build time.

using System;
using System.ComponentModel;
using System.Diagnostics;
using System.IO;
using System.Reflection;
using System.Text;

[assembly: AssemblyTitle("卫戍协议：工坊")]
[assembly: AssemblyProduct("卫戍协议：工坊")]
[assembly: AssemblyDescription("卫戍协议：工坊 启动器")]
[assembly: AssemblyCopyright("GPL-3.0-or-later")]

static class Launcher
{
    const string Title = "卫戍协议：工坊";
    const string DataFolderName = "Stronghold-Protocol-Workshop";

    static int Main(string[] args)
    {
        try { Console.OutputEncoding = new UTF8Encoding(false); } catch (IOException) { }
        try { Console.Title = Title; } catch (IOException) { }
        // Ctrl+C reaches node directly (same console); the server shuts down and we report its exit code.
        Console.CancelKeyPress += (sender, e) => { e.Cancel = true; };

        int code;
        try { code = Run(args); }
        catch (Exception e) { Console.WriteLine("启动失败：" + e.Message); code = 1; }
        if (code != 0) Pause();
        return code;
    }

    static int Run(string[] args)
    {
        string root = AppDomain.CurrentDomain.BaseDirectory;
        string app = Path.Combine(root, "app");
        string script = Path.Combine(app, Path.Combine("scripts", "launch.mjs"));
        if (!File.Exists(script))
        {
            Console.WriteLine("没有找到游戏文件：" + script);
            Console.WriteLine("请把压缩包完整解压到一个文件夹，再双击其中的「启动游戏.exe」。");
            return 1;
        }

        string bundledNode = Path.Combine(root, Path.Combine("node", "node.exe"));
        var psi = new ProcessStartInfo
        {
            // Without the bundled Node (a --no-node bundle) CreateProcess finds node.exe on PATH.
            FileName = File.Exists(bundledNode) ? bundledNode : "node",
            Arguments = JoinArguments(script, BuildInfo.LaunchArguments, args),
            WorkingDirectory = app,
            UseShellExecute = false,
        };
        string saves = SavesDirectory(root);
        if (saves != null)
        {
            psi.EnvironmentVariables["SP_INDEPENDENT_DIRECTORY"] = saves;
            Console.WriteLine("存档位置：" + saves);
        }

        Process node;
        try { node = Process.Start(psi); }
        catch (Win32Exception)
        {
            Console.WriteLine("找不到 Node.js：本包没有自带 node\\node.exe，请先安装 Node.js 22 或更高版本。");
            Console.WriteLine("下载：https://nodejs.org/zh-cn/download");
            return 1;
        }
        using (node)
        {
            node.WaitForExit();
            return node.ExitCode;
        }
    }

    /// <summary>The per-user saves folder, or null when the user already chose one (or there is no profile).</summary>
    static string SavesDirectory(string root)
    {
        if (!string.IsNullOrEmpty(Environment.GetEnvironmentVariable("SP_INDEPENDENT_DIRECTORY"))) return null;
        string local = Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData);
        if (string.IsNullOrEmpty(local)) return null;
        string saves = Path.Combine(local, Path.Combine(DataFolderName, "independent-sessions"));
        string legacy = Path.Combine(root, Path.Combine("app", Path.Combine("runtime", "independent-sessions")));
        try
        {
            if (HasFiles(legacy) && !HasFiles(saves))
            {
                CopyTree(legacy, saves);
                Console.WriteLine("已把旧版本的存档复制到新的存档位置。");
            }
            Directory.CreateDirectory(saves);
            return saves;
        }
        // The compiler that ships with Windows is C# 5: no exception filters, so the two cases are spelled out.
        catch (IOException e) { return SavesUnavailable(saves, e); }
        catch (UnauthorizedAccessException e) { return SavesUnavailable(saves, e); }
    }

    static string SavesUnavailable(string saves, Exception e)
    {
        Console.WriteLine("无法使用存档目录 " + saves + "：" + e.Message + "（本次存档保存在游戏目录里）");
        return null;
    }

    static bool HasFiles(string dir)
    {
        return Directory.Exists(dir) && Directory.GetFiles(dir, "*", SearchOption.AllDirectories).Length > 0;
    }

    static void CopyTree(string from, string to)
    {
        Directory.CreateDirectory(to);
        foreach (string file in Directory.GetFiles(from)) File.Copy(file, Path.Combine(to, Path.GetFileName(file)), false);
        foreach (string dir in Directory.GetDirectories(from)) CopyTree(dir, Path.Combine(to, Path.GetFileName(dir)));
    }

    static string JoinArguments(string script, string[] fixedArgs, string[] userArgs)
    {
        var sb = new StringBuilder(Quote(script));
        foreach (string a in fixedArgs) sb.Append(' ').Append(Quote(a));
        foreach (string a in userArgs) sb.Append(' ').Append(Quote(a));
        return sb.ToString();
    }

    /// <summary>Quote one argument so the CRT / CommandLineToArgvW split gives it back unchanged.</summary>
    static string Quote(string a)
    {
        if (a.Length > 0 && a.IndexOfAny(new[] { ' ', '\t', '\n', '\v', '"' }) < 0) return a;
        var sb = new StringBuilder("\"");
        for (int i = 0; ; i++)
        {
            int slashes = 0;
            while (i < a.Length && a[i] == '\\') { slashes++; i++; }
            if (i == a.Length) { sb.Append('\\', slashes * 2); break; }
            if (a[i] == '"') sb.Append('\\', slashes * 2 + 1).Append('"');
            else sb.Append('\\', slashes).Append(a[i]);
        }
        return sb.Append('"').ToString();
    }

    static void Pause()
    {
        if (Console.IsInputRedirected) return;
        Console.WriteLine();
        Console.WriteLine("按任意键关闭窗口…");
        try { Console.ReadKey(true); } catch (InvalidOperationException) { }
    }
}
